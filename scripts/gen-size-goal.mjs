// Regenerates SIZE_GOAL in src/sim/data/week.ts (E-21) from b_steady2 play.
//
// b_steady2 (tests/longsim/run.ts: b_steady with a second hire, standard
// prices) plays 40 weeks on seeds 1, 42, 7 and 2026 of every difficulty, each
// run in its own vitest process (tests/longsim/size-goal.gen.ts). Every week
// from SIZE_GOAL_FIRST_WEEK gives a sample: the total upgrade levels at the
// week's start, the week's revenue and its score profit (weekProfit, the
// upgrade charge taken off). The standard of a level is then:
//   1. the median revenue and median profit of the samples at that level;
//   2. made non-decreasing in levels (isotonic fit, weighted by sample count),
//      so a bigger shop never has a smaller target;
//   3. between sampled levels, the straight line between their fitted values;
//   4. below the lowest sampled level, the line through the lowest sampled
//      level and the one EXTEND_SPAN levels above it, kept at least
//      MIN_SHARE of the lowest sampled level;
//   5. above the highest sampled level (b_steady2 stops buying at 71), its
//      value: levels standard play never reaches add no standard takings.
// Row = { revenue: 1.0 x standard revenue, profit: 1.5 x standard profit },
// rounded to 100.000 đồng.
//
// Usage: node scripts/gen-size-goal.mjs [--samples file.json] [--save file.json] [--dry]
//   --samples reads samples saved before instead of playing; --save writes them;
//   --dry prints the table without writing week.ts.
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const DIFFICULTIES = ['easy', 'normal', 'hard'];
const SEEDS = [1, 42, 7, 2026];
const FIRST_WEEK = 9; // SIZE_GOAL_FIRST_WEEK
const MAX_LEVELS = 77; // SIZE_GOAL_MAX_LEVELS
const REVENUE_RATIO = 1.0;
const PROFIT_RATIO = 1.5;
const EXTEND_SPAN = 12;
const MIN_SHARE = 0.5;
const WEEK_TS = 'src/sim/data/week.ts';
const BEGIN = '// BEGIN SIZE_GOAL_ROWS (generated by scripts/gen-size-goal.mjs, do not edit by hand)';
const END = '// END SIZE_GOAL_ROWS';

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

/** Plays b_steady2 on one difficulty and seed and returns its weeks as [week, start levels, revenue, profit]. */
function sample(difficulty, seed) {
  return new Promise((resolve, reject) => {
    const child = spawn('npx', ['vitest', 'run', '--configLoader', 'runner', '--config', 'tests/longsim/vitest.config.ts'], {
      env: { ...process.env, LONGSIM_GEN: '1', GEN_DIFFICULTY: difficulty, GEN_SEED: String(seed) },
      stdio: ['ignore', 'pipe', 'inherit'],
    });
    let out = '';
    child.stdout.on('data', (d) => (out += d));
    child.on('close', (code) => {
      const line = out.split('\n').find((l) => l.startsWith('SIZE_GOAL_ROWS '));
      if (code !== 0 || !line) reject(new Error(`${difficulty} seed ${seed}: sampler exited ${code}\n${out}`));
      else resolve(JSON.parse(line.slice('SIZE_GOAL_ROWS '.length)));
    });
  });
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const n = s.length;
  return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
};

/** Weighted isotonic (non-decreasing) fit by pool-adjacent-violators. */
function isotonic(values, weights) {
  const blocks = [];
  values.forEach((v, i) => {
    blocks.push({ v, w: weights[i], n: 1 });
    while (blocks.length > 1 && blocks.at(-2).v > blocks.at(-1).v) {
      const b = blocks.pop();
      const a = blocks.at(-1);
      a.v = (a.v * a.w + b.v * b.w) / (a.w + b.w);
      a.w += b.w;
      a.n += b.n;
    }
  });
  return blocks.flatMap((b) => Array(b.n).fill(b.v));
}

/** Standard values for levels 0..MAX_LEVELS from fitted [level, value] points (rules 3-5). */
function extend(points) {
  const at = (level) => {
    if (level >= points.at(-1)[0]) return points.at(-1)[1];
    const i = points.findIndex(([l]) => l >= level);
    if (points[i][0] === level) return points[i][1];
    if (i === 0) {
      const [l0, v0] = points[0];
      const v1 = at(l0 + EXTEND_SPAN);
      return Math.max(MIN_SHARE * v0, v0 - ((v1 - v0) / EXTEND_SPAN) * (l0 - level));
    }
    const [la, va] = points[i - 1];
    const [lb, vb] = points[i];
    return va + ((vb - va) * (level - la)) / (lb - la);
  };
  return Array.from({ length: MAX_LEVELS + 1 }, (_, level) => at(level));
}

const round = (x) => Math.round(x / 100_000) * 100_000;

function table(samples, difficulty) {
  const byLevel = new Map();
  for (const run of samples.filter((s) => s.difficulty === difficulty)) {
    if (run.bankruptDay) throw new Error(`${difficulty} seed ${run.seed}: b_steady2 went bankrupt on day ${run.bankruptDay}`);
    for (const [week, levels, revenue, profit] of run.rows) {
      if (week < FIRST_WEEK) continue;
      if (!byLevel.has(levels)) byLevel.set(levels, []);
      byLevel.get(levels).push([revenue, profit]);
    }
  }
  const levels = [...byLevel.keys()].sort((a, b) => a - b);
  const weights = levels.map((l) => byLevel.get(l).length);
  const fit = (k) => {
    const fitted = isotonic(levels.map((l) => median(byLevel.get(l).map((x) => x[k]))), weights);
    return extend(levels.map((l, i) => [l, fitted[i]]));
  };
  const revenue = fit(0);
  const profit = fit(1);
  return revenue.map((r, i) => [round(REVENUE_RATIO * r), round(PROFIT_RATIO * profit[i])]);
}

function source(tables) {
  const lines = [BEGIN, 'const SIZE_GOAL_ROWS: Readonly<Record<Difficulty, readonly (readonly [number, number])[]>> = {'];
  for (const d of DIFFICULTIES) {
    lines.push(`  ${d}: [`);
    for (let i = 0; i < tables[d].length; i += 4) {
      const chunk = tables[d].slice(i, i + 4).map(([r, p]) => `[${r}, ${p}]`).join(', ');
      lines.push(`    ${chunk}, // ${i}..${Math.min(i + 3, tables[d].length - 1)}`);
    }
    lines.push('  ],');
  }
  lines.push('};', END);
  return lines.join('\n');
}

const samples = opt('--samples')
  ? JSON.parse(readFileSync(opt('--samples'), 'utf8'))
  : await Promise.all(DIFFICULTIES.flatMap((d) => SEEDS.map((s) => sample(d, s))));
if (opt('--save')) writeFileSync(opt('--save'), JSON.stringify(samples));
const tables = Object.fromEntries(DIFFICULTIES.map((d) => [d, table(samples, d)]));
const block = source(tables);
if (args.includes('--dry')) {
  console.log(block);
} else {
  const ts = readFileSync(WEEK_TS, 'utf8');
  const from = ts.indexOf(BEGIN);
  const to = ts.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${WEEK_TS}: no ${BEGIN} ... ${END} block`);
  writeFileSync(WEEK_TS, ts.slice(0, from) + block + ts.slice(to + END.length));
  console.log(`SIZE_GOAL written to ${WEEK_TS}`);
}
