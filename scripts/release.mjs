#!/usr/bin/env node
// Bumps the game version from the Conventional Commits since the latest v*
// tag: updates package.json, package-lock.json and CHANGELOG.md, commits
// "chore(release): vX.Y.Z" and tags vX.Y.Z. Never pushes.
//
//   node scripts/release.mjs            release if there is something to release
//   node scripts/release.mjs --dry-run  only print the next version
//
// Exit 0 with "release: none" when nothing needs a release (or there is no v*
// tag yet), so deploy-pages.sh can call it on every run.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HEADER = /^(\w+)(?:\(([^)]*)\))?(!)?:\s*(.+)$/;
const BREAKING_FOOTER = /^BREAKING[ -]CHANGE:/m;
const LEVELS = ['patch', 'minor', 'major'];

/** Groups in CHANGELOG.md, in order (Keep a Changelog names). */
export const CHANGELOG_GROUPS = [
  { title: 'Added', has: (c) => c.type === 'feat' },
  { title: 'Fixed', has: (c) => c.type === 'fix' },
  // perf, plus breaking commits of other types such as "refactor!:".
  { title: 'Changed', has: (c) => c.type === 'perf' || (c.breaking && c.type !== 'feat' && c.type !== 'fix') },
];

export const CHANGELOG_HEADER =
  '# Changelog\n\nNotable changes to Coffee Shop Tycoon 3D, generated by `scripts/release.mjs` from Conventional Commits.\n';

/**
 * Parses a commit message. Returns null for messages that are not
 * Conventional Commits (merge commits, "deploy: …" has no effect either).
 */
export function parseCommit(message, hash = '') {
  const [subject = '', ...rest] = message.trim().split('\n');
  const m = HEADER.exec(subject.trim());
  if (!m) return null;
  return {
    hash,
    type: m[1].toLowerCase(),
    scope: m[2] || null,
    breaking: Boolean(m[3]) || BREAKING_FOOTER.test(rest.join('\n')),
    summary: m[4].trim(),
  };
}

/** Bump level a commit asks for, or null if it does not change the version. */
export function commitLevel(commit) {
  if (!commit) return null;
  if (commit.breaking) return 'major';
  if (commit.type === 'feat') return 'minor';
  if (commit.type === 'fix' || commit.type === 'perf') return 'patch';
  return null;
}

/** Highest bump level across commits, or null. */
export function bumpLevel(commits) {
  let best = -1;
  for (const c of commits) best = Math.max(best, LEVELS.indexOf(commitLevel(c)));
  return best < 0 ? null : LEVELS[best];
}

/**
 * Next version after `current` for the given parsed commits; `current` itself
 * when nothing qualifies. While on 0.x a breaking change bumps the minor.
 */
export function nextVersion(current, commits) {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(current);
  if (!m) throw new Error(`not a x.y.z version: ${current}`);
  let [major, minor, patch] = m.slice(1).map(Number);
  let level = bumpLevel(commits);
  if (level === 'major' && major === 0) level = 'minor';
  if (level === 'major') return `${major + 1}.0.0`;
  if (level === 'minor') return `${major}.${minor + 1}.0`;
  if (level === 'patch') return `${major}.${minor}.${patch + 1}`;
  return current;
}

/** One "## [x.y.z] - date" section; only commits that bump the version are listed. */
export function changelogSection(version, date, commits) {
  const lines = [`## [${version}] - ${date}`];
  for (const group of CHANGELOG_GROUPS) {
    const items = commits.filter((c) => c && commitLevel(c) && group.has(c));
    if (!items.length) continue;
    lines.push('', `### ${group.title}`, '');
    for (const c of items) {
      const flag = c.breaking ? '**BREAKING** ' : '';
      const scope = c.scope ? `**${c.scope}:** ` : '';
      const hash = c.hash ? ` (${c.hash.slice(0, 7)})` : '';
      lines.push(`- ${flag}${scope}${c.summary}${hash}`);
    }
  }
  return lines.join('\n') + '\n';
}

/** Inserts a section above the newest release, keeping the header. */
export function insertChangelog(existing, section) {
  const text = existing && existing.trim() ? existing : CHANGELOG_HEADER;
  const at = text.search(/^## /m);
  if (at < 0) return `${text.replace(/\n*$/, '')}\n\n${section}`;
  return `${text.slice(0, at)}${section}\n${text.slice(at)}`;
}

function git(args, cwd) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function main(argv) {
  const dryRun = argv.includes('--dry-run');
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  let tag;
  try {
    tag = git(['describe', '--tags', '--abbrev=0', '--match', 'v[0-9]*'], root);
  } catch {
    console.log('release: none (no v* tag yet). Tag the current release once, e.g.:');
    console.log('  git tag -a v0.1.0 <commit of the 0.1.0 deploy> -m v0.1.0 && git push origin v0.1.0');
    return;
  }
  const raw = git(['log', '--format=%H%x1f%B%x1e', `${tag}..HEAD`], root);
  const commits = raw
    .split('\x1e')
    .map((r) => r.trim())
    .filter(Boolean)
    .map((r) => {
      const [hash, message = ''] = r.split('\x1f');
      return parseCommit(message, hash);
    })
    .filter(Boolean);

  const pkgPath = join(root, 'package.json');
  const current = JSON.parse(readFileSync(pkgPath, 'utf8')).version;
  const next = nextVersion(current, commits);
  if (next === current) {
    console.log(`release: none (no feat/fix/perf since ${tag}, version ${current})`);
    return;
  }
  if (dryRun) {
    console.log(`release: ${current} -> ${next} (since ${tag}, dry run)`);
    return;
  }

  const files = ['package.json', 'package-lock.json', 'CHANGELOG.md'];
  const dirty = git(['status', '--porcelain', '--', ...files], root);
  if (dirty) throw new Error(`commit or discard changes first:\n${dirty}`);
  if (git(['tag', '--list', `v${next}`], root)) throw new Error(`tag v${next} already exists`);

  execFileSync('npm', ['version', next, '--no-git-tag-version', '--allow-same-version'], { cwd: root, stdio: 'ignore' });
  const changelogPath = join(root, 'CHANGELOG.md');
  const existing = existsSync(changelogPath) ? readFileSync(changelogPath, 'utf8') : '';
  const date = new Date().toISOString().slice(0, 10);
  writeFileSync(changelogPath, insertChangelog(existing, changelogSection(next, date, commits)));

  git(['add', '--', ...files], root);
  git(['commit', '-q', '-m', `chore(release): v${next}`, '--', ...files], root);
  git(['tag', '-a', `v${next}`, '-m', `v${next}`], root);
  console.log(`release: ${current} -> ${next} (since ${tag}); committed and tagged v${next}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    console.error(`release: ${err instanceof Error ? err.message : err}`);
    process.exit(1);
  }
}
