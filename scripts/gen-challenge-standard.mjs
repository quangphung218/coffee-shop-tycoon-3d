// Regenerates CHALLENGE_STANDARD in src/sim/data/challenges.ts (E-24) from d_manage play.
//
// d_manage (tests/longsim/run.ts: buys every upgrade it can, a team of 4,
// high prices from week 9) plays 40 weeks on seeds 1, 42, 7 and 2026 of every
// difficulty, each run in its own vitest process (tests/longsim/size-goal.gen.ts
// with GEN_BOT=d_manage). Every week from CHALLENGE_SCALE_FIRST_WEEK gives a
// sample at its SIZE_GOAL row index (sizeGoalRowIndex, the same row as the week
// goal of E-24 part A): customers served, regulars served and cups sold per
// menu item over the week. A week in which d_manage chases a template is left
// out of that template's numbers: served_week and regular_visits weeks (it runs
// campaigns) for served and regulars, sell_item weeks (it narrows the menu) for
// cups sold. The standard of a row is then, as in scripts/gen-size-goal.mjs:
//   1. the median of the samples at that row;
//   2. made non-decreasing in rows (isotonic fit, weighted by sample count);
//   3. between sampled rows, the straight line between their fitted values;
//   4. below the lowest sampled row, the line through it and the row
//      EXTEND_SPAN above it, kept at least MIN_SHARE of the lowest sampled row;
//   5. above the highest sampled row, its value.
// Values are rounded to whole numbers. served_week, sell_item, regular_visits
// and calm_day (per day: served / 7) ask CHALLENGE_ANCHOR_FACTORS of the row
// from CHALLENGE_ANCHOR_FIRST_WEEK (earlier weeks keep the E-19 own average).
//
// Usage: node scripts/gen-challenge-standard.mjs [--samples file.json] [--save file.json] [--dry]
//   --samples reads samples saved before instead of playing; --save writes them;
//   --dry prints the table without writing challenges.ts.
import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const DIFFICULTIES = ['easy', 'normal', 'hard'];
const SEEDS = [1, 42, 7, 2026];
const FIRST_WEEK = 9; // CHALLENGE_SCALE_FIRST_WEEK
const MAX_ROW = 77; // SIZE_GOAL_MAX_LEVELS
const EXTEND_SPAN = 12;
const MIN_SHARE = 0.5;
const CHALLENGES_TS = 'src/sim/data/challenges.ts';
const BEGIN = '// BEGIN CHALLENGE_STANDARD_ROWS (generated by scripts/gen-challenge-standard.mjs, do not edit by hand)';
const END = '// END CHALLENGE_STANDARD_ROWS';

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

/** Plays d_manage on one difficulty and seed and returns the sampler's JSON line. */
function sample(difficulty, seed) {
  return new Promise((resolve, reject) => {
    const child = spawn('npx', ['vitest', 'run', '--configLoader', 'runner', '--config', 'tests/longsim/vitest.config.ts'], {
      env: { ...process.env, LONGSIM_GEN: '1', GEN_BOT: 'd_manage', GEN_DIFFICULTY: difficulty, GEN_SEED: String(seed) },
      stdio: ['ignore', 'pipe', 'inherit'],
    });
    let out = '';
    child.stdout.on('data', (d) => (out += d));
    child.on('close', (code) => {
      const line = out.split('\n').find((l) => l.startsWith('SIZE_GOAL_ROWS '));
      if (code !== 0 || !line) reject(new Error(`${difficulty} seed ${seed}: sampler exited ${code}\n${out}`));
      else resolve(JSON.parse(line.slice('SIZE_GOAL_ROWS '.length)));
    });
  });
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const n = s.length;
  return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
};

/** Weighted isotonic (non-decreasing) fit by pool-adjacent-violators. */
function isotonic(values, weights) {
  const blocks = [];
  values.forEach((v, i) => {
    blocks.push({ v, w: weights[i], n: 1 });
    while (blocks.length > 1 && blocks.at(-2).v > blocks.at(-1).v) {
      const b = blocks.pop();
      const a = blocks.at(-1);
      a.v = (a.v * a.w + b.v * b.w) / (a.w + b.w);
      a.w += b.w;
      a.n += b.n;
    }
  });
  return blocks.flatMap((b) => Array(b.n).fill(b.v));
}

/** Values for rows 0..MAX_ROW from fitted [row, value] points (rules 3-5). */
function extend(points) {
  const at = (row) => {
    if (row >= points.at(-1)[0]) return points.at(-1)[1];
    const i = points.findIndex(([r]) => r >= row);
    if (points[i][0] === row) return points[i][1];
    if (i === 0) {
      const [r0, v0] = points[0];
      const v1 = at(r0 + EXTEND_SPAN);
      return Math.max(MIN_SHARE * v0, v0 - ((v1 - v0) / EXTEND_SPAN) * (r0 - row));
    }
    const [ra, va] = points[i - 1];
    const [rb, vb] = points[i];
    return va + ((vb - va) * (row - ra)) / (rb - ra);
  };
  return Array.from({ length: MAX_ROW + 1 }, (_, row) => at(row));
}

/** Standard column for rows 0..MAX_ROW from [row, value] samples. */
function column(samples, what) {
  const byRow = new Map();
  for (const [row, value] of samples) {
    if (!byRow.has(row)) byRow.set(row, []);
    byRow.get(row).push(value);
  }
  const rows = [...byRow.keys()].sort((a, b) => a - b);
  if (rows.length === 0) throw new Error(`${what}: no samples`);
  const fitted = isotonic(
    rows.map((r) => median(byRow.get(r))),
    rows.map((r) => byRow.get(r).length),
  );
  return extend(rows.map((r, i) => [r, fitted[i]])).map((v) => Math.round(v));
}

/** Sampler row: [week, levels, revenue, profit, revenueTarget, profitTarget, score, row, served, regulars, sold, challenge]. */
function table(samples, difficulty, items) {
  const weeks = [];
  for (const run of samples.filter((s) => s.difficulty === difficulty)) {
    if (run.bankruptDay) throw new Error(`${difficulty} seed ${run.seed}: d_manage went bankrupt on day ${run.bankruptDay}`);
    for (const r of run.rows) if (r[0] >= FIRST_WEEK) weeks.push(r);
  }
  const crowd = weeks.filter((r) => r[11] !== 'served_week' && r[11] !== 'regular_visits');
  const menu = weeks.filter((r) => r[11] !== 'sell_item');
  const cols = [
    column(crowd.map((r) => [r[7], r[8]]), `${difficulty} served`),
    column(crowd.map((r) => [r[7], r[9]]), `${difficulty} regulars`),
    ...items.map((id) => column(menu.map((r) => [r[7], r[10][id] ?? 0]), `${difficulty} ${id}`)),
  ];
  return Array.from({ length: MAX_ROW + 1 }, (_, i) => cols.map((c) => c[i]));
}

function source(items, tables) {
  const lines = [
    BEGIN,
    `const CHALLENGE_STANDARD_ITEMS: readonly MenuItemId[] = [${items.map((id) => `'${id}'`).join(', ')}];`,
    'const CHALLENGE_STANDARD_ROWS: Readonly<Record<Difficulty, readonly (readonly number[])[]>> = {',
  ];
  for (const d of DIFFICULTIES) {
    lines.push(`  ${d}: [`);
    tables[d].forEach((row, i) => lines.push(`    [${row.join(', ')}], // ${i}`));
    lines.push('  ],');
  }
  lines.push('};', END);
  return lines.join('\n');
}

const samples = opt('--samples')
  ? JSON.parse(readFileSync(opt('--samples'), 'utf8'))
  : await Promise.all(DIFFICULTIES.flatMap((d) => SEEDS.map((s) => sample(d, s))));
if (opt('--save')) writeFileSync(opt('--save'), JSON.stringify(samples));
const items = [...new Set(samples.flatMap((s) => s.rows.flatMap((r) => Object.keys(r[10]))))].sort();
const tables = Object.fromEntries(DIFFICULTIES.map((d) => [d, table(samples, d, items)]));
const block = source(items, tables);
if (args.includes('--dry')) {
  console.log(block);
} else {
  const ts = readFileSync(CHALLENGES_TS, 'utf8');
  const from = ts.indexOf(BEGIN);
  const to = ts.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${CHALLENGES_TS}: no ${BEGIN} ... ${END} block`);
  writeFileSync(CHALLENGES_TS, ts.slice(0, from) + block + ts.slice(to + END.length));
  console.log(`CHALLENGE_STANDARD written to ${CHALLENGES_TS}`);
}
