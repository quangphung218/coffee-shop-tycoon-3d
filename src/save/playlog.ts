import type { Phase } from '../sim/types';
import { defaultStorage, type StorageLike } from './storage';

export const PLAYLOG_KEY = 'cst3d:playlog';
export const PLAYLOG_VERSION = 1;
/** Oldest lines are dropped beyond this. */
export const PLAYLOG_MAX_ENTRIES = 1000;

export type PlayLogKind =
  | 'run_start'
  | 'phase'
  | 'day_end'
  | 'week_end'
  | 'hidden'
  | 'visible'
  | 'quit_to_menu'
  | 'replay';

export type PlayLogPhase = Phase | 'menu' | 'week_end';

/**
 * One anonymous play-log line. Only these fields are ever stored: no shop
 * name, user agent or anything else that could identify the player.
 */
export interface PlayLogEntry {
  v: 1;
  /** Random id per run, generated by the caller (e.g. crypto.randomUUID). */
  run: string;
  kind: PlayLogKind;
  day: number;
  phase: PlayLogPhase;
  /** Game minutes since midnight. */
  minute: number;
  /** Epoch ms. */
  at: number;
}

/** Last line of one run: where and when the player stopped. */
export interface PlayLogStop {
  run: string;
  kind: PlayLogKind;
  day: number;
  phase: PlayLogPhase;
  minute: number;
  at: number;
}

export const PLAYLOG_FIELDS: readonly (keyof PlayLogEntry)[] = ['v', 'run', 'kind', 'day', 'phase', 'minute', 'at'];

const KINDS: readonly PlayLogKind[] = [
  'run_start',
  'phase',
  'day_end',
  'week_end',
  'hidden',
  'visible',
  'quit_to_menu',
  'replay',
];
const PHASES: readonly PlayLogPhase[] = ['preparation', 'opening', 'peak', 'closing', 'report', 'menu', 'week_end'];
/** Run ids are UUIDs or base36; anything else (a shop name, say) drops the line. */
const RUN_ID = /^[a-z0-9-]{1,40}$/i;

/** Outcome of reading the log: entries, or why storage could not be read. */
export type PlayLogStatus =
  | { ok: true; entries: PlayLogEntry[] }
  | { ok: false; reason: 'blocked' | 'corrupt' };

function num(v: unknown): number | null {
  const n = typeof v === 'string' && v.trim() !== '' ? Number(v) : v;
  return typeof n === 'number' && Number.isFinite(n) ? n : null;
}

/** Keeps only whitelisted fields with valid values; null drops the line. */
export function sanitizePlayLogEntry(raw: unknown, now?: number): PlayLogEntry | null {
  if (typeof raw !== 'object' || raw === null) return null;
  const r = raw as Record<string, unknown>;
  const run = typeof r.run === 'string' ? r.run.trim() : '';
  if (!RUN_ID.test(run)) return null;
  if (!KINDS.includes(r.kind as PlayLogKind)) return null;
  if (!PHASES.includes(r.phase as PlayLogPhase)) return null;
  const day = num(r.day);
  const minute = num(r.minute);
  const at = num(r.at) ?? (now !== undefined ? num(now) : null);
  if (day === null || day < 0 || minute === null || minute < 0 || at === null || at < 0) return null;
  return {
    v: 1,
    run,
    kind: r.kind as PlayLogKind,
    day: Math.floor(day),
    phase: r.phase as PlayLogPhase,
    minute,
    at: Math.floor(at),
  };
}

/**
 * Never throws. A missing log is an empty one; storage that refuses to be read
 * is 'blocked', text that is not a log is 'corrupt'.
 */
export function readPlayLogStatus(storage: StorageLike = defaultStorage()): PlayLogStatus {
  let text: string | null;
  try {
    text = storage.getItem(PLAYLOG_KEY);
  } catch {
    return { ok: false, reason: 'blocked' };
  }
  if (text === null) return { ok: true, entries: [] };
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    return { ok: false, reason: 'corrupt' };
  }
  const entries = typeof data === 'object' && data !== null ? (data as Record<string, unknown>).entries : undefined;
  if (!Array.isArray(entries)) return { ok: false, reason: 'corrupt' };
  const out: PlayLogEntry[] = [];
  for (const e of entries) {
    const clean = sanitizePlayLogEntry(e);
    if (clean) out.push(clean);
  }
  return { ok: true, entries: out.slice(-PLAYLOG_MAX_ENTRIES) };
}

/** Never throws; missing, blocked or broken data yields an empty log. */
export function readPlayLog(storage: StorageLike = defaultStorage()): PlayLogEntry[] {
  const status = readPlayLogStatus(storage);
  return status.ok ? status.entries : [];
}

/**
 * Appends one line after whitelisting it. `now` fills `at` when the entry has
 * none. Returns false when the line is invalid or storage is unavailable/full.
 */
export function appendPlayLog(
  entry: Partial<PlayLogEntry> | Record<string, unknown>,
  storage: StorageLike = defaultStorage(),
  now: number = Date.now(),
): boolean {
  const clean = sanitizePlayLogEntry(entry, now);
  if (!clean) return false;
  try {
    const entries = readPlayLog(storage);
    entries.push(clean);
    storage.setItem(PLAYLOG_KEY, JSON.stringify({ v: PLAYLOG_VERSION, entries: entries.slice(-PLAYLOG_MAX_ENTRIES) }));
    return true;
  } catch {
    return false;
  }
}

/** Returns false when storage is unavailable. */
export function clearPlayLog(storage: StorageLike = defaultStorage()): boolean {
  try {
    storage.removeItem(PLAYLOG_KEY);
    return true;
  } catch {
    return false;
  }
}

/** Last line of each run, in order of each run's first appearance. */
export function playLogLastStops(entries: readonly PlayLogEntry[]): PlayLogStop[] {
  const last = new Map<string, PlayLogEntry>();
  for (const e of entries) last.set(e.run, e);
  return [...last.values()].map(({ run, kind, day, phase, minute, at }) => ({ run, kind, day, phase, minute, at }));
}

/** Pretty JSON for download: every line plus where each run stopped. */
export function exportPlayLog(storage: StorageLike = defaultStorage(), now: number = Date.now()): string {
  const entries = readPlayLog(storage);
  return JSON.stringify(
    { version: PLAYLOG_VERSION, exportedAt: now, entries, lastStops: playLogLastStops(entries) },
    null,
    2,
  );
}
