/** Templates whose numbers scale from CHALLENGE_SCALE_FIRST_WEEK (scaledChallengeTarget, anchoredChallengeTarget). */
export type ScaledChallengeId = Extract<WeekChallengeId, 'served_week' | 'sell_item' | 'regular_visits' | 'calm_day'>;

/** First week whose counting challenges scale; weeks before it keep the WEEK_CHALLENGES numbers. */
export const CHALLENGE_SCALE_FIRST_WEEK = 9;

/** Finished weeks, read from the day history, whose values a scaled challenge averages (before CHALLENGE_ANCHOR_FIRST_WEEK). */
export const CHALLENGE_SCALE_WEEKS = 4;

/**
 * Share of the previous weeks' average a scaled challenge asks for before
 * CHALLENGE_ANCHOR_FIRST_WEEK (E-19): per week for served_week (customers),
 * sell_item (cups of the item) and regular_visits; per day for calm_day (its
 * minServed).
 */
export const CHALLENGE_SCALE_FACTORS: Readonly<Record<ScaledChallengeId, number>> = {
  served_week: 0.95,
  sell_item: 0.95,
  regular_visits: 1,
  calm_day: 0.9,
};

/**
 * First week whose counting challenges read the CHALLENGE_STANDARD row of the
 * week's SIZE_GOAL row instead of the shop's own average (E-24). Earlier weeks
 * keep the E-19 rule, so weeks 5-20 (and their E-16 bands) are unchanged.
 */
export const CHALLENGE_ANCHOR_FIRST_WEEK = 21;

/**
 * Share of the CHALLENGE_STANDARD row a scaled challenge asks for from
 * CHALLENGE_ANCHOR_FIRST_WEEK: per week for served_week (customers), sell_item
 * (cups of the item) and regular_visits; per day (the week's customers / 7)
 * for calm_day's minServed.
 */
export const CHALLENGE_ANCHOR_FACTORS: Readonly<Record<ScaledChallengeId, number>> = {
  served_week: 1,
  sell_item: 2,
  regular_visits: 1,
  calm_day: 1,
};

/** Scaled numbers are rounded to these steps. */
export const CHALLENGE_SCALE_STEPS: Readonly<Record<ScaledChallengeId, number>> = {
  served_week: 50,
  sell_item: 10,
  regular_visits: 5,
  calm_day: 10,
};

/** True for the templates whose numbers scale. */
export function isScaledChallenge(id: WeekChallengeId): id is ScaledChallengeId {
  return id in CHALLENGE_SCALE_FACTORS;
}

function factoredTarget(id: ScaledChallengeId, value: number, factor: number): number {
  const def = WEEK_CHALLENGES[id];
  const floor = id === 'calm_day' ? (def.minServed ?? 0) : def.target;
  const step = CHALLENGE_SCALE_STEPS[id];
  return Math.max(floor, Math.round((value * factor) / step) * step);
}

/**
 * Number a scaled challenge asks for before CHALLENGE_ANCHOR_FIRST_WEEK given
 * the previous weeks' average value (per week, or per day for calm_day): the
 * average times its CHALLENGE_SCALE_FACTORS, rounded to its step, never below
 * the template's number (`target`, or `minServed` for calm_day).
 */
export function scaledChallengeTarget(id: ScaledChallengeId, average: number): number {
  return factoredTarget(id, average, CHALLENGE_SCALE_FACTORS[id]);
}

/**
 * Number a scaled challenge asks for from CHALLENGE_ANCHOR_FIRST_WEEK given its
 * CHALLENGE_STANDARD value (per week, or per day for calm_day): the value times
 * its CHALLENGE_ANCHOR_FACTORS, rounded to its step, never below the
 * template's number.
 */
export function anchoredChallengeTarget(id: ScaledChallengeId, standard: number): number {
  return factoredTarget(id, standard, CHALLENGE_ANCHOR_FACTORS[id]);
}

