/** What d_manage does in a week at a SIZE_GOAL row (CHALLENGE_STANDARD). */
export interface ChallengeStandardRow {
  /** Customers served over the week. */
  served: number;
  /** Regulars served over the week. */
  regulars: number;
  /** Cups sold of each menu item over the week. */
  sold: Readonly<Partial<Record<MenuItemId, number>>>;
}

function standardRows(difficulty: Difficulty): ChallengeStandardRow[] {
  return CHALLENGE_STANDARD_ROWS[difficulty].map(([served, regulars, ...sold]) => ({
    served: served!,
    regulars: regulars!,
    sold: Object.fromEntries(CHALLENGE_STANDARD_ITEMS.map((id, i) => [id, sold[i]!])),
  }));
}

/**
 * Standard numbers of the scaled challenges by difficulty, indexed by the
 * week's SIZE_GOAL row (sizeGoalRowIndex in src/sim/data/week.ts, the same row
 * the week goal reads, 0..SIZE_GOAL_MAX_LEVELS): what d_manage
 * (tests/longsim/run.ts: every upgrade it can buy, a team of 4, high prices)
 * makes in a week at that row (E-24). Regenerate with
 * `node scripts/gen-challenge-standard.mjs`, which documents how rows it never
 * reaches are filled in.
 */
export const CHALLENGE_STANDARD: Readonly<Record<Difficulty, readonly ChallengeStandardRow[]>> = {
  easy: standardRows('easy'),
  normal: standardRows('normal'),
  hard: standardRows('hard'),
};

/** CHALLENGE_STANDARD row `row`, clamped to the table. */
export function challengeStandard(difficulty: Difficulty, row: number): ChallengeStandardRow {
  const rows = CHALLENGE_STANDARD[difficulty];
  const i = Math.min(rows.length - 1, Math.max(0, Math.floor(Number.isFinite(row) ? row : 0)));
  return rows[i]!;
}
